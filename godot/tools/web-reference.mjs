#!/usr/bin/env node
/**
 * web-reference.mjs — numbers the WEB build computes, for the Godot port to
 * match exactly.
 *
 * The road (v4.58), Toko's bowl (v4.61), Kello's cut (v4.63), the doors
 * (v4.65), who takes the board (v4.66) and the families' standing (v4.67)
 * are deterministic from the save:
 * the road rolls FNV-1a over contentId|block|label (`deterministicRoll` in
 * web/js/v3/state.js) and the board prices come from `market/model.mjs`'s
 * seeded xmur3 + mulberry32. A port that is "close" is a different road and a
 * different price, and the only honest test of "the same" is to run the web
 * modules themselves and write down what they say. This does that, read-only,
 * and `tests/test_story.gd` holds the Godot build to every number.
 *
 *   node tools/web-reference.mjs           write tests/fixtures/web-reference.json
 *   node tools/web-reference.mjs --check   fail if the web says something else now
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const godot = resolve(here, '..');
const repo = resolve(godot, '..');
const out = resolve(godot, 'tests/fixtures/web-reference.json');
const mod = (p) => import(pathToFileURL(resolve(repo, 'web/js/v3', p)).href);

const {
  createState, deterministicRoll, advanceSchedule, currentSchedule, currentEncounter, chooseEncounter,
  choiceStatus, recordFight, fightsToday, forecastEnding,
  aatamiFights, stepBackIfReady, fighters, requirementStatus,
} = await mod('state.js');
const { createBattleState } = await mod('battle.js');
const { offerDoors, takeDoor, isDoorBlock, escalation } = await mod('doors.js');
const { settleCut } = await mod('story.js');
const { rungOf, settleStanding } = await mod('standing.js');
const { turnPlan } = await mod('chapter.js');
const { rollRoad, resolveRoad, choiceOpen, clockLabel } = await mod('road.js');
const { board } = await mod('board.js');
const { buyBowl, tokoTip } = await mod('toko.js');
const json = async (p) => JSON.parse(await readFile(resolve(repo, p), 'utf8'));
const content = await json('content/era1-slice-v1.json');
const map = await json('map/kallio-era1-2003-v1.json');
const roadEvents = await json('content/road-events-v1.json');
const story = await json('content/act1-story-v1.json');
const doorsCanon = await json('content/doors-v1.json');
const families = await json('content/families-v1.json');
const data = {
  content,
  encounters: new Map(content.encounters.map(e => [e.id, e])),
  missions: new Map(content.missions.map(m => [m.id, m])),
  battles: new Map(content.battles.map(b => [b.id, b])),
  equipment: new Map(content.equipment.map(e => [e.id, e])),
  anchors: new Map(map.anchors.map(a => [a.id, a])),
  sites: new Map(map.sites.map(s => [s.id, s])),
  crew: new Map(content.crew.map(c => [c.id, c])),
};

const ref = { note: 'Generated by godot/tools/web-reference.mjs from the web modules. Do not hand-edit.' };

// 1. The roll itself, at a few blocks and labels.
const s0 = createState(content);
ref.rolls = [];
for (const [block, label] of [[0, 'road:1:fire'], [2, 'road:3:fire'], [5, 'road:7:phase'], [9, 'road:12:pick'], [13, 'x']]) {
  s0.scheduleIndex = block;
  ref.rolls.push({ block, label, value: deterministicRoll(s0, label) });
}

// 2. A road walked journey by journey: two before block 2 (nothing fires),
// sixteen at block 2 (tier 0), then someone recruited at block 7 (tier 1) and
// sixteen more. Every event is answered with its first open choice.
const s = createState(content);
const journey = { path: ['piritori', 'siltasaari'], destination: 'siltasaari' };
ref.road = [];
const step = () => {
  const ev = rollRoad(s, data, roadEvents, journey);
  const row = { block: s.scheduleIndex, journeys: s.road.journeys, since: s.road.since,
    event: ev ? ev.id : '', phase: ev ? s.road.pending.phase : '' };
  if (ev) {
    const choice = ev.choices.find(c => choiceOpen(c, s, data).ok);
    resolveRoad(s, data, roadEvents, choice.id);
    Object.assign(row, { choice: choice.id, minutes: s.road.minutes,
      clock: clockLabel(s, content.schedule[s.scheduleIndex], roadEvents), cash: s.cash });
  }
  ref.road.push(row);
};
step(); step();
s.scheduleIndex = 2;
for (let i = 0; i < 16; i++) step();
s.scheduleIndex = 7;
s.recruited.push('crew-slot-runner');
for (let i = 0; i < 16; i++) step();
ref.road_seen = s.road.seen;

// 3. The board on day one at Vaasankatu, having stood at Piritori, and a bowl.
const b = createState(content);
b.selectedAnchor = 'vaasankatu';
b.seen = { piritori: 0, vaasankatu: 0 };
ref.board = board(b, data).rows.map(r => ({ id: r.id, level: r.shown.level,
  buy: r.truth.buy, sell: r.truth.sell }));
ref.tip = tokoTip(b, data).id;
buyBowl(b, data);
const row = board(b, data).rows.find(r => r.id === ref.tip);
ref.heard = { id: row.id, level: row.shown.level, low_buy: row.shown.lowBuy, high_buy: row.shown.highBuy,
  low_sell: row.shown.lowSell, high_sell: row.shown.highSell, heard: row.heard, visited: row.visited, age: row.age };
b.scheduleIndex += 1;
ref.second_tip = buyBowl(b, data).anchorId;
b.scheduleIndex += 5;
ref.after_six = board(b, data).rows.find(r => r.id === ref.tip).shown.level;
b.scheduleIndex += 10;
ref.after_sixteen = board(b, data).rows.find(r => r.id === ref.tip).shown.level;

// 4. Kello's cut (v4.63): taken on day one and never ended, the whole slice
// walked block by block the way `advanceAndSettle` walks it — the cut settles
// after every block that ends a night, and rolls at the block after it.
const k = createState(content);
k.flags.push('thursday-cut');
ref.cut = [];
while (currentSchedule(k, content)) {
  const ended = currentSchedule(k, content);
  advanceSchedule(k, data);
  if (ended.block !== 'night') continue;
  const r = settleCut(k, story);
  ref.cut.push({ block: k.scheduleIndex, payments: k.cut.payments, paid: r.paid, found_out: r.foundOut,
    roll: deterministicRoll(k, `kello-cut:${k.cut.payments}`) });
}

// 5. The chapter turn (v4.64): the plan the web reads off a fresh save.
ref.chapter_plan = turnPlan(createState(content), content).map(r => ({ key: r.key, rule: r.rule, now: r.now, next: r.next }));

// 6. The doors (v4.65): the offers the web rolls for a door block, across
// ten content ids (the roll's first term), the three door blocks, with and
// without packs on hand (a sale door needs one), and with the day's two
// fights already spent (no fight door is forced then).
const doorBlocks = content.schedule.map((slot, i) => (slot.door ? i : -1)).filter(i => i >= 0);
ref.door_blocks = doorBlocks;
ref.doors = [];
const contentIdOf = seed => (seed === 0 ? content.id : `${content.id}#${seed}`);
for (let seed = 0; seed < 10; seed += 1) {
  for (const block of doorBlocks) {
    for (const [piri, fights] of [[0, 0], [2, 0], [2, 2]]) {
      const d = createState(content);
      d.contentId = contentIdOf(seed);
      d.scheduleIndex = block;
      d.stock.piri = piri;
      for (let f = 0; f < fights; f += 1) recordFight(d, content);
      ref.doors.push({ content_id: d.contentId, block, piri, fights, fights_today: fightsToday(d, content),
        offers: offerDoors(d, data, doorsCanon).map(o => ({ template: o.template, anchor: o.anchor })) });
    }
  }
}
// A door is taken once a chapter: take the first at the first door block, and
// the next door block's roll no longer holds it.
ref.door_chain = [];
for (let seed = 0; seed < 5; seed += 1) {
  const d = createState(content);
  d.contentId = contentIdOf(seed);
  d.stock.piri = 2;
  const row = { content_id: d.contentId, steps: [] };
  for (const block of doorBlocks) {
    d.scheduleIndex = block;
    const offers = offerDoors(d, data, doorsCanon);
    const took = takeDoor(d, data, doorsCanon, offers[0].template, roadEvents);
    row.steps.push({ block, offers: offers.map(o => ({ template: o.template, anchor: o.anchor })),
      took: took.ok ? took.offer.template : '', encounter: took.ok ? took.encounter.id : '' });
  }
  ref.door_chain.push(row);
}

// 6b. A bad deal escalates (answer 25): every choice with `escalates`, over
// twenty saves, with three crew (a fight), with one hire (Aatami makes two
// who can fight, answer 24: a two-a-side door fights, a three-a-side one
// costs its stakes), with none (Aatami alone: the door's losing stakes), and
// with the day's two fights spent (never).
ref.escalation = [];
const crew3 = content.crew.slice(0, 3).map(c => c.id);
for (const t of doorsCanon.templates) {
  for (const c of t.choices.filter(ch => ch.escalates)) {
    for (let seed = 0; seed < 20; seed += 1) {
      for (const [hired, fights] of [[3, 0], [1, 0], [0, 0], [3, 2]]) {
        const e = createState(content);
        e.contentId = contentIdOf(seed);
        e.scheduleIndex = doorBlocks[0];
        e.recruited = crew3.slice(0, hired); e.deployed = [...e.recruited];
        for (let f = 0; f < fights; f += 1) recordFight(e, content);
        const r = escalation(e, data, doorsCanon, t.id, c.id);
        ref.escalation.push({ content_id: e.contentId, door: t.id, choice: c.id, crew: hired, fights,
          result: r ? (r.battle ? `battle:${r.battle}` : 'effects') : '' });
      }
    }
  }
}

// 6c. Who takes the board (answers 24 and 26, COMBAT.md §9.9.1, GDD §16):
// Aatami fights through chapters 1 and 2 whatever crew he can field, and
// from chapter 3 (The Supplier) he stays out; the first fight he can stay out
// of is a one-time beat, and after it he stays out for good, even if the
// chapter reads 1 again. Each row: the hires, the chapter, whether he has
// already stepped back, and what the web says — does he fight, who the
// fighters are, the fight requirements, the beat a fight starting now would
// open on, and the lineup of both fights.
ref.fighters = [];
for (const [hired, chapter, stepped] of [[0, 1, false], [1, 1, false], [2, 1, false], [3, 1, false], [4, 1, false],
  [3, 2, false], [1, 3, false], [3, 3, false], [1, 1, true], [0, 1, true]]) {
  const f = createState(content);
  if (stepped) {
    f.chapter = 3;
    stepBackIfReady(f, content);
  }
  f.chapter = chapter;
  f.recruited = content.crew.slice(0, hired).map(c => c.id); f.deployed = [...f.recruited];
  const row = {
    hired: f.recruited, chapter, stepped,
    aatami_fights: aatamiFights(f, content),
    fighters: fighters(f, data).map(x => x.id),
    requirements: Object.fromEntries(['fighters>=2', 'fighters>=3', 'deployed-crew>=2'].map(r => [r, requirementStatus(r, f, data).ok])),
    lineups: {},
  };
  for (const id of ['battle-karhupuisto-2v2', 'battle-courtyard-3v3']) {
    const crew = fighters(f, data);
    row.lineups[id] = crew.length >= data.battles.get(id).player_deployed
      ? createBattleState(data.battles.get(id), crew, f, data).players.map(p => p.id) : null;
  }
  row.beat = stepBackIfReady(f, content);
  row.fighters_after_beat = fighters(f, data).map(x => x.id);
  ref.fighters.push(row);
}

// 7. The whole ten-day chapter, walked the way web/test/doors.mjs walks it:
// every block, the first door taken on a free block, the last open choice
// that starts no fight. What the web took, block by block, and where the
// road points at the end. The families are loaded, as they are in the game
// (v4.67): a walk that insults one closes its doors on the next free block.
{
  const walk = { ...data, families };
  const w = createState(content);
  ref.chapter_walk = [];
  for (let guard = 0; guard < 40 && currentSchedule(w, content); guard += 1) {
    let door = '';
    if (isDoorBlock(w, content) && !w.doors.taken[w.scheduleIndex]) {
      const offers = offerDoors(w, walk, doorsCanon);
      door = takeDoor(w, walk, doorsCanon, offers[0].template, roadEvents).offer.template;
    }
    const enc = currentEncounter(w, walk);
    w.selectedAnchor = currentSchedule(w, content).anchor_id;
    const quiet = [...enc.choices].reverse().find(c => choiceStatus(c, w, walk).ok && !c.effects.some(fx => fx.startsWith('start-battle')));
    chooseEncounter(w, enc, quiet, walk);
    ref.chapter_walk.push({ block: w.scheduleIndex, door, encounter: enc.id, choice: quiet.id });
    advanceSchedule(w, walk);
  }
  ref.chapter_walk_end = { cleared: w.chapterCleared, outcome: w.lastEndingOutcome ?? '',
    forecast: w.flags.find(f => f.startsWith('memory:pasila-forecast:')) ?? '', ending: forecastEnding(w, walk)?.id ?? '' };
}

// 8. The families' standing (v4.67). The ladder at every number from +3 to
// -6; the door boards with a family Wary or worse (its doors never offered)
// or Friendly (its work always on the board, rolled under `door:favoured`),
// across ten saves, the three door blocks and with the day's fights spent;
// and the night's settlement over scripted runs of relationship numbers,
// both families walked in canon order, one event a night.
ref.rungs = [];
for (let v = 3; v >= -6; v -= 1) ref.rungs.push({ value: v, rung: rungOf(v, families).id });
const standingData = { ...data, families };
ref.standing_doors = [];
for (let seed = 0; seed < 10; seed += 1) {
  for (const block of doorBlocks) {
    for (const [mc, jade] of [[-1, 0], [0, -2], [2, 0], [0, 2], [2, 2], [-1, 2], [2, -4]]) {
      for (const fights of [0, 2]) {
        const d = createState(content);
        d.contentId = contentIdOf(seed);
        d.scheduleIndex = block;
        d.stock.piri = 2;
        d.relationships.mccormick_family = mc;
        d.relationships.jade_lantern_network = jade;
        for (let f = 0; f < fights; f += 1) recordFight(d, content);
        ref.standing_doors.push({ content_id: d.contentId, block, mccormick: mc, jade, fights,
          offers: offerDoors(d, standingData, doorsCanon).map(o => ({ template: o.template, anchor: o.anchor })) });
      }
    }
  }
}
ref.standing_nights = [];
for (const [name, nights] of [
  ['one family down the ladder', [[0, 0], [-1, 0], [-2, 0], [-2, 0], [-1, 0], [-2, 0], [-3, 0], [-3, 0], [-3, 0], [-3, 0], [-4, 0], [-4, 0], [-2, 0], [0, 0]]],
  ['two families at once', [[-2, -2], [-2, -2], [-2, -2], [-3, -3], [-3, -3], [-3, -3], [-3, -3], [-4, -4], [-4, -4], [-4, -3], [-1, -3], [-1, -3]]],
  ['a vendetta holds the night', [[-4, -2], [-4, -2], [-4, -3], [-4, -3], [0, -3], [0, -3], [2, -2], [2, 2]]],
]) {
  const st = createState(content);
  const row = { name, nights: [] };
  for (const [mc, jade] of nights) {
    st.relationships.mccormick_family = mc;
    st.relationships.jade_lantern_network = jade;
    const r = settleStanding(st, families);
    row.nights.push({ mccormick: mc, jade, raise: r.raise ?? '', warnings: r.warnings,
      warned: { ...st.standing.warned }, demanded: { ...st.standing.demanded } });
  }
  ref.standing_nights.push(row);
}

const text = JSON.stringify(ref, null, 1) + '\n';
if (process.argv.includes('--check')) {
  let have = '';
  try { have = await readFile(out, 'utf8'); } catch { /* missing */ }
  if (have !== text) {
    console.error('WEB REFERENCE DRIFT: tests/fixtures/web-reference.json no longer matches the web modules.');
    console.error('Run: node tools/web-reference.mjs  — then make the Godot port agree.');
    process.exit(1);
  }
  console.log(`WEB REFERENCE OK: ${ref.road.length} journeys, ${ref.board.length} board rows, tip ${ref.tip}, ${ref.cut.length} nights of the cut, ${ref.chapter_plan.length} turn rows, ${ref.doors.length} door boards, ${ref.escalation.length} escalation rolls, ${ref.fighters.length} lineups, ${ref.chapter_walk.length} blocks walked, ${ref.standing_doors.length} standing boards, ${ref.standing_nights.length} runs of nights.`);
} else {
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, text);
  console.log(`wrote tests/fixtures/web-reference.json (${ref.road.length} journeys, ${ref.board.length} board rows).`);
}
