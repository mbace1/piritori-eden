#!/usr/bin/env node
/**
 * web-reference.mjs — numbers the WEB build computes, for the Godot port to
 * match exactly.
 *
 * The road (v4.58) and Toko's bowl (v4.61) are deterministic from the save:
 * the road rolls FNV-1a over contentId|block|label (`deterministicRoll` in
 * web/js/v3/state.js) and the board prices come from `market/model.mjs`'s
 * seeded xmur3 + mulberry32. A port that is "close" is a different road and a
 * different price, and the only honest test of "the same" is to run the web
 * modules themselves and write down what they say. This does that, read-only,
 * and `tests/test_story.gd` holds the Godot build to every number.
 *
 *   node tools/web-reference.mjs           write tests/fixtures/web-reference.json
 *   node tools/web-reference.mjs --check   fail if the web says something else now
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const godot = resolve(here, '..');
const repo = resolve(godot, '..');
const out = resolve(godot, 'tests/fixtures/web-reference.json');
const mod = (p) => import(pathToFileURL(resolve(repo, 'web/js/v3', p)).href);

const { createState, deterministicRoll } = await mod('state.js');
const { rollRoad, resolveRoad, choiceOpen, clockLabel } = await mod('road.js');
const { board } = await mod('board.js');
const { buyBowl, tokoTip } = await mod('toko.js');
const json = async (p) => JSON.parse(await readFile(resolve(repo, p), 'utf8'));
const content = await json('content/era1-slice-v1.json');
const map = await json('map/kallio-era1-2003-v1.json');
const roadEvents = await json('content/road-events-v1.json');
const data = {
  content,
  equipment: new Map(content.equipment.map(e => [e.id, e])),
  anchors: new Map(map.anchors.map(a => [a.id, a])),
  sites: new Map(map.sites.map(s => [s.id, s])),
  crew: new Map(content.crew.map(c => [c.id, c])),
};

const ref = { note: 'Generated by godot/tools/web-reference.mjs from the web modules. Do not hand-edit.' };

// 1. The roll itself, at a few blocks and labels.
const s0 = createState(content);
ref.rolls = [];
for (const [block, label] of [[0, 'road:1:fire'], [2, 'road:3:fire'], [5, 'road:7:phase'], [9, 'road:12:pick'], [13, 'x']]) {
  s0.scheduleIndex = block;
  ref.rolls.push({ block, label, value: deterministicRoll(s0, label) });
}

// 2. A road walked journey by journey: two before block 2 (nothing fires),
// sixteen at block 2 (tier 0), then someone recruited at block 7 (tier 1) and
// sixteen more. Every event is answered with its first open choice.
const s = createState(content);
const journey = { path: ['piritori', 'siltasaari'], destination: 'siltasaari' };
ref.road = [];
const step = () => {
  const ev = rollRoad(s, data, roadEvents, journey);
  const row = { block: s.scheduleIndex, journeys: s.road.journeys, since: s.road.since,
    event: ev ? ev.id : '', phase: ev ? s.road.pending.phase : '' };
  if (ev) {
    const choice = ev.choices.find(c => choiceOpen(c, s, data).ok);
    resolveRoad(s, data, roadEvents, choice.id);
    Object.assign(row, { choice: choice.id, minutes: s.road.minutes,
      clock: clockLabel(s, content.schedule[s.scheduleIndex], roadEvents), cash: s.cash });
  }
  ref.road.push(row);
};
step(); step();
s.scheduleIndex = 2;
for (let i = 0; i < 16; i++) step();
s.scheduleIndex = 7;
s.recruited.push('crew-slot-runner');
for (let i = 0; i < 16; i++) step();
ref.road_seen = s.road.seen;

// 3. The board on day one at Vaasankatu, having stood at Piritori, and a bowl.
const b = createState(content);
b.selectedAnchor = 'vaasankatu';
b.seen = { piritori: 0, vaasankatu: 0 };
ref.board = board(b, data).rows.map(r => ({ id: r.id, level: r.shown.level,
  buy: r.truth.buy, sell: r.truth.sell }));
ref.tip = tokoTip(b, data).id;
buyBowl(b, data);
const row = board(b, data).rows.find(r => r.id === ref.tip);
ref.heard = { id: row.id, level: row.shown.level, low_buy: row.shown.lowBuy, high_buy: row.shown.highBuy,
  low_sell: row.shown.lowSell, high_sell: row.shown.highSell, heard: row.heard, visited: row.visited, age: row.age };
b.scheduleIndex += 1;
ref.second_tip = buyBowl(b, data).anchorId;
b.scheduleIndex += 5;
ref.after_six = board(b, data).rows.find(r => r.id === ref.tip).shown.level;
b.scheduleIndex += 10;
ref.after_sixteen = board(b, data).rows.find(r => r.id === ref.tip).shown.level;

const text = JSON.stringify(ref, null, 1) + '\n';
if (process.argv.includes('--check')) {
  let have = '';
  try { have = await readFile(out, 'utf8'); } catch { /* missing */ }
  if (have !== text) {
    console.error('WEB REFERENCE DRIFT: tests/fixtures/web-reference.json no longer matches the web modules.');
    console.error('Run: node tools/web-reference.mjs  — then make the Godot port agree.');
    process.exit(1);
  }
  console.log(`WEB REFERENCE OK: ${ref.road.length} journeys, ${ref.board.length} board rows, tip ${ref.tip}.`);
} else {
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, text);
  console.log(`wrote tests/fixtures/web-reference.json (${ref.road.length} journeys, ${ref.board.length} board rows).`);
}
