// stage-template.mjs — draw the canonical arena onto a blank 16:9 frame.
//
// The grid is the fixed thing in this game and a stage is art produced to sit
// under it (formation_battle.gd, ARENA). This renders that arena as an SVG
// template: hand it to whoever or whatever draws a location, and the floor
// comes back in the right place, at the right angle, at the right size.
//
// It reads the numbers OUT of formation_battle.gd rather than repeating them,
// because a template that disagrees with the engine is worse than no template.
//
//   node tools/stage-template.mjs            > stage-template.svg
//   node tools/stage-template.mjs --check    verify it can still parse the source
//
// See STAGE_SPEC.md for what an artist is being asked for.

import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(resolve(here, '../scenes/formation_battle.gd'), 'utf8');

function num(re, label) {
  const m = src.match(re);
  if (!m) {
    console.error(`stage-template: could not read ${label} from formation_battle.gd`);
    process.exit(1);
  }
  return parseFloat(m[1]);
}

// const ARENA := {"c": Vector2(0.500, 0.620), "fwd": 0.175, "lane": 0.145}
const cx   = num(/const ARENA := \{"c": Vector2\(([\d.]+),/, 'arena centre x');
const cy   = num(/const ARENA := \{"c": Vector2\([\d.]+,\s*([\d.]+)\)/, 'arena centre y');
const fwd  = num(/const ARENA := .*"fwd":\s*([\d.]+)/, 'arena fwd');
const lane = num(/const ARENA := .*"lane":\s*([\d.]+)/, 'arena lane');

// The two isometric axes, exactly as the board uses them.
const FWD  = num(/const FORWARD := Vector2\(([-\d.]+),/, 'FORWARD.x') ;
const FWDY = num(/const FORWARD := Vector2\([-\d.]+,\s*([-\d.]+)\)/, 'FORWARD.y');
const LANX = num(/const LANE_AXIS := Vector2\(([-\d.]+),/, 'LANE_AXIS.x');
const LANY = num(/const LANE_AXIS := Vector2\([-\d.]+,\s*([-\d.]+)\)/, 'LANE_AXIS.y');

// A 16:9 frame, and the plate is what remains above the command console.
// 188 of 768 is the console's own height in formation_battle.gd.
const W = 1920, H = 1080;
const CONSOLE = Math.round((188 / 768) * H);
const PLATE_H = H - CONSOLE;

const c = { x: cx * W, y: cy * PLATE_H };
const f = { x: FWD * fwd * W, y: FWDY * fwd * W };
const l = { x: LANX * lane * W, y: LANY * lane * W };

const pt = (sf, sl, k = 1) =>
  `${(c.x + k * sf * f.x + k * sl * l.x).toFixed(1)},${(c.y + k * sf * f.y + k * sl * l.y).toFixed(1)}`;
const quad = [pt(-1, -1), pt(1, -1), pt(1, 1), pt(-1, 1)].join(' ');

// THE FLOOR MUST BE BIGGER THAN THE ARENA.
//
// The first stage built from this template put its ground exactly on the arena,
// and the far corner then clipped onto the building: a unit standing in the back
// rank had its feet past the edge of the floor. Units stand ON the outer cells,
// and a figure is drawn from its feet upward, so the ground has to run past the
// board on every side.
const MARGIN = 1.22;
const floorQuad = [pt(-1, -1, MARGIN), pt(1, -1, MARGIN),
                   pt(1, 1, MARGIN), pt(-1, 1, MARGIN)].join(' ');

if (process.argv.includes('--check')) {
  console.log(`TEMPLATE OK: arena centre ${cx},${cy} fwd ${fwd} lane ${lane}`);
  process.exit(0);
}

process.stdout.write(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <!-- Generated by tools/stage-template.mjs from formation_battle.gd's ARENA.
       Do not hand-edit: it is derived, and a template that disagrees with the
       engine is worse than no template. -->
  <rect width="${W}" height="${H}" fill="#101418"/>

  <!-- The command console. Anything drawn here is never seen in play. -->
  <rect x="0" y="${PLATE_H}" width="${W}" height="${CONSOLE}" fill="#05070a"/>
  <text x="24" y="${PLATE_H + 44}" font-family="monospace" font-size="26" fill="#4a5560">
    COMMAND CONSOLE — covered in play, do not compose anything here
  </text>

  <!-- THE FLOOR. Ground must be flat and clear out to at least here. -->
  <polygon points="${floorQuad}" fill="#1d4a90" fill-opacity="0.16"
           stroke="#4f86d8" stroke-width="3" stroke-dasharray="18 12"/>
  <text x="${c.x}" y="${(c.y - f.y * MARGIN - 22).toFixed(1)}" text-anchor="middle"
        font-family="monospace" font-size="22" fill="#4f86d8">
    GROUND MUST REACH THIS DASHED EDGE — buildings begin beyond it, never on it
  </text>

  <!-- THE ARENA. Units stand on the outer cells of this shape. -->
  <polygon points="${quad}" fill="#2a68d0" fill-opacity="0.22"
           stroke="#7fb2ff" stroke-width="4"/>
  <text x="${c.x}" y="${c.y}" text-anchor="middle" font-family="monospace"
        font-size="30" fill="#bcd8ff">PLAYABLE FLOOR</text>
  <text x="${c.x}" y="${c.y + 38}" text-anchor="middle" font-family="monospace"
        font-size="21" fill="#7fb2ff">flat, unobstructed, edges on these two diagonals</text>

  <!-- Headroom: figures stand roughly a tile and a half tall from their feet,
       so the far rank needs clear air above the arena's far edge. -->
  <line x1="${(c.x + f.x - l.x).toFixed(1)}" y1="${(c.y + f.y - l.y).toFixed(1)}"
        x2="${(c.x + f.x + l.x).toFixed(1)}" y2="${(c.y + f.y + l.y).toFixed(1)}"
        stroke="#ffd24a" stroke-width="3" stroke-dasharray="14 10"/>
  <text x="${c.x}" y="${(c.y + f.y - 26)}" text-anchor="middle"
        font-family="monospace" font-size="21" fill="#ffd24a">
    far edge — keep ~140px of clear air above this line for the back rank
  </text>
</svg>
`);
